-- Phase 2 session 1: idempotent local PostgreSQL foundation.
-- Never store HR rows, personal data or application secrets in this script.
BEGIN;

CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS marts;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS audit.source_files (
    source_file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_filename TEXT NOT NULL,
    sha256 CHAR(64) NOT NULL UNIQUE,
    byte_size BIGINT NOT NULL CHECK (byte_size >= 0),
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT source_sha256_hex CHECK (sha256 ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS audit.load_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file_id BIGINT NOT NULL REFERENCES audit.source_files(source_file_id),
    status TEXT NOT NULL DEFAULT 'RUNNING'
        CHECK (status IN ('RUNNING','SUCCEEDED','FAILED','SKIPPED')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    rows_expected INTEGER CHECK (rows_expected IS NULL OR rows_expected >= 0),
    rows_loaded INTEGER CHECK (rows_loaded IS NULL OR rows_loaded >= 0),
    error_message TEXT,
    CONSTRAINT load_batch_time_order CHECK (
        finished_at IS NULL OR finished_at >= started_at
    )
);

CREATE TABLE IF NOT EXISTS audit.quality_results (
    quality_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES audit.load_batches(batch_id),
    check_id TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('PASS','FAIL','REVIEW')),
    affected_count BIGINT CHECK (affected_count IS NULL OR affected_count >= 0),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT quality_results_batch_check_unique UNIQUE (batch_id, check_id)
);

CREATE INDEX IF NOT EXISTS ix_load_batches_source_started
    ON audit.load_batches(source_file_id, started_at DESC);
CREATE INDEX IF NOT EXISTS ix_quality_results_batch_status
    ON audit.quality_results(batch_id, status);

COMMIT;
