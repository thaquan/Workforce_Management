-- Phase 4: persistent operational metadata; safe to run repeatedly.
BEGIN;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS audit.pipeline_runs (
    pipeline_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_mode TEXT NOT NULL CHECK (run_mode IN ('FULL', 'QUALITY_ONLY')),
    status TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    stage TEXT NOT NULL DEFAULT 'START',
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    ingest_batch_id BIGINT REFERENCES audit.load_batches(batch_id),
    error_type TEXT,
    note JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT pipeline_run_time_order CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE IF NOT EXISTS audit.data_quality_results (
    quality_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_run_id BIGINT NOT NULL REFERENCES audit.pipeline_runs(pipeline_run_id),
    check_id TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('PASS','REVIEW','FAIL')),
    affected_count BIGINT NOT NULL CHECK (affected_count >= 0),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pipeline_quality_unique UNIQUE (pipeline_run_id, check_id)
);

CREATE TABLE IF NOT EXISTS audit.pipeline_metrics (
    pipeline_run_id BIGINT NOT NULL REFERENCES audit.pipeline_runs(pipeline_run_id),
    metric_name TEXT NOT NULL,
    metric_value NUMERIC(22,6) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (pipeline_run_id, metric_name)
);

CREATE INDEX IF NOT EXISTS ix_pipeline_runs_status_time
    ON audit.pipeline_runs(status, started_at DESC);
CREATE INDEX IF NOT EXISTS ix_pipeline_quality_run_status
    ON audit.data_quality_results(pipeline_run_id, status);
COMMIT;
